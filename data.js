  function uid(prefix) {
    return prefix + '_' + Date.now().toString(36) + Math.random().toString(36).slice(2, 7);
  }

  function episodesForComic(data, comicId) {
    return data.episodes.filter(function (e) { return e.comicId === comicId; })
      .sort(function (a, b) { return a.index - b.index; });
  }

  function isUnlocked(data, episodeId) {
    return data.unlocks.some(function (u) { return u.episodeId === episodeId; });
  }

  function unlockRecordFor(data, episodeId) {
    return data.unlocks.find(function (u) { return u.episodeId === episodeId; }) || null;
  }

  function totalCoinsSpent(data) {
    return data.unlocks.reduce(function (sum, u) {
      if (typeof u.coinsPaid === 'number') return sum + u.coinsPaid;
      var ep2 = data.episodes.find(function (e) { return e.id === u.episodeId; });
      return sum + (ep2 ? ep2.coinPrice : 0);
    }, 0);
  }

